//! File uploads: one-shot multipart uploads, resumable chunked uploads, and downloads, all
//! streamed through [`Storage`].
//!
//! Resumable protocol (any chunk size up to the configured maximum, in order):
//!
//! 1. `POST   {api}/uploads` with `{"filename", "size", "content_type"}` creates a session.
//! 2. `PATCH  {api}/uploads/{id}` with header `Upload-Offset: N` and the raw bytes appends a
//!    chunk. The offset must equal what the server has; otherwise it answers 409 with the
//!    offset it expects.
//! 3. `GET    {api}/uploads/{id}` reports the current offset, which is how a client resumes
//!    after a dropped connection or a restart on either side.
//! 4. The chunk that reaches `size` completes the upload and returns the stored file.
//!
//! Session state lives in the database and chunks in the storage backend, so an upload
//! survives server restarts and can continue on a different instance.

